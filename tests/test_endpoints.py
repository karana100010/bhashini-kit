def to_wav16k(audio_base64):
    """TTS WAV (8 kHz float32 or int16) -> base64 16 kHz mono int16 WAV, pure Python."""
    raw, fmt, data, i = base64.b64decode(audio_base64), None, None, 12
    while i < len(raw):
        chunk, size = raw[i:i + 4], struct.unpack('<I', raw[i + 4:i + 8])[0]
        if chunk == b'fmt ':
            fmt = struct.unpack('<HHIIHH', raw[i + 8:i + 24])
        elif chunk == b'data':
            data = raw[i + 8:i + 8 + size]
        i += 8 + size + (size & 1)
    tag, channels, rate, _, _, bits = fmt
    samples = array.array('f' if tag == 3 else 'h', data[:len(data) - len(data) % (bits // 8)])
    floats = list(samples) if tag == 3 else [v / 32768 for v in samples]
    floats = floats[::channels]
    ratio, out = 16000 / rate, array.array('h')
    for k in range(int(len(floats) * ratio)):
        p = k / ratio
        a = int(p)
        b = min(a + 1, len(floats) - 1)
        v = floats[a] + (floats[b] - floats[a]) * (p - a)
        out.append(max(-32768, min(32767, int(v * 32767))))
    return pcm_wav(out.tobytes())


def pcm_wav(pcm):
    buffer = io.BytesIO()
    with wave.open(buffer, 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(16000)
        w.writeframes(pcm)
    return base64.b64encode(buffer.getvalue()).decode()


def pcm_of(wav_base64):
    with wave.open(io.BytesIO(base64.b64decode(wav_base64))) as w:
        return w.readframes(w.getnframes())


def test(name):
    def wrap(fn):
        start = time.time()
        try:
            detail = fn()
            results.append((name, 'PASS', time.time() - start, detail or ''))
        except Exception as error:  # noqa: BLE001 - report every failure and carry on
            results.append((name, 'FAIL', time.time() - start, f'{type(error).__name__}: {error}'))
            if os.environ.get('VERBOSE'):
                traceback.print_exc()
        return fn
    return wrap


