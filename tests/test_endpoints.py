@test('stream: live ASR over socket')
def _():
    async def go():
        events = {'partial': [], 'final': [], 'error': [], 'ready': [], 'end': []}
        async with aiohttp.ClientSession() as session:
            async with session.ws_connect(f'{STREAM}/ws/asr', timeout=30) as ws:
                await ws.send_str(json.dumps({'type': 'start', 'language': 'hi'}))
                reader = asyncio.ensure_future(read(ws, events))
                for _ in range(100):
                    if events['ready'] or events['error']:
                        break
                    await asyncio.sleep(0.1)
                assert events['ready'], events['error'] or 'no ready'
                pcm = pcm_of(TTS['hi'])
                for i in range(0, len(pcm), 3200):  # 100 ms chunks at real-time speed
                    await ws.send_bytes(pcm[i:i + 3200])
                    await asyncio.sleep(0.1)
                await asyncio.sleep(1.5)
                await ws.send_str(json.dumps({'type': 'stop'}))
                await asyncio.wait_for(reader, 20)
        assert not events['error'], events['error']
        assert events['final'] and events['final'][-1].strip(), events
        return f"{len(events['partial'])} partials → {events['final'][-1]}"

    async def read(ws, events):
        async for message in ws:
            if message.type != aiohttp.WSMsgType.TEXT:
                break
            data = json.loads(message.data)
            events[data['type']].append(data.get('text') or data.get('message') or '')
            if data['type'] in ('end', 'error'):
                break
    return asyncio.run(go())


